//! The drag loop for a window that gets no mouse messages.
//!
//! OLE's drag loop moves on when an input message reaches the thread's queue,
//! and its own drop source learns from those messages that the button went
//! up. A `WinUI` window is told about the pointer another way and its thread's
//! queue stays empty: the loop would stand still, and the drag would only
//! end on Escape. So here a helper thread posts a mouse move at the pointer's
//! place every few milliseconds for as long as the drag lasts, and the drop
//! source reads the button and Escape from the keyboard state.
#![allow(unsafe_code)]
#![allow(
    clippy::inline_always,
    clippy::ref_as_ptr,
    reason = "code generated by `windows::core::implement`"
)]

use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::Duration;

use windows::Win32::Foundation::{
    BOOL, DRAGDROP_S_CANCEL, DRAGDROP_S_DROP, DRAGDROP_S_USEDEFAULTCURSORS, LPARAM, POINT, S_OK,
    WPARAM,
};
use windows::Win32::System::Ole::{DROPEFFECT, IDropSource, IDropSource_Impl};
use windows::Win32::System::SystemServices::{MK_LBUTTON, MODIFIERKEYS_FLAGS};
use windows::Win32::System::Threading::GetCurrentThreadId;
use windows::Win32::UI::Input::KeyboardAndMouse::{
    GetAsyncKeyState, VK_ESCAPE, VK_LBUTTON, VK_RBUTTON,
};
use windows::Win32::UI::WindowsAndMessaging::{
    GetCursorPos, GetSystemMetrics, PostThreadMessageW, SM_SWAPBUTTON, WM_MOUSEMOVE,
};
use windows::core::{HRESULT, implement};

/// How often the drag loop is woken.
const PULSE: Duration = Duration::from_millis(30);

/// What the drag loop should do next.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Next {
    Continue,
    /// Drop where the pointer is.
    Drop,
    /// Give the drag up.
    Cancel,
}

/// Escape gives the drag up; the button going up drops.
const fn decide(escape_down: bool, button_down: bool) -> Next {
    if escape_down {
        Next::Cancel
    } else if button_down {
        Next::Continue
    } else {
        Next::Drop
    }
}

/// Whether the key is down right now, whatever the message queue holds.
fn is_down(key: u16) -> bool {
    // SAFETY: no preconditions.
    unsafe { GetAsyncKeyState(i32::from(key)) }.cast_unsigned() & 0x8000 != 0
}

/// A drop source that reads the mouse button and Escape as they are.
#[implement(IDropSource)]
struct PolledSource;

impl IDropSource_Impl for PolledSource_Impl {
    fn QueryContinueDrag(&self, escape_pressed: BOOL, _keys: MODIFIERKEYS_FLAGS) -> HRESULT {
        // With the buttons swapped, the main one is the right one.
        // SAFETY: no preconditions.
        let swapped = unsafe { GetSystemMetrics(SM_SWAPBUTTON) } != 0;
        let button = if swapped { VK_RBUTTON } else { VK_LBUTTON };
        match decide(
            escape_pressed.as_bool() || is_down(VK_ESCAPE.0),
            is_down(button.0),
        ) {
            Next::Continue => S_OK,
            Next::Drop => DRAGDROP_S_DROP,
            Next::Cancel => DRAGDROP_S_CANCEL,
        }
    }

    fn GiveFeedback(&self, _effect: DROPEFFECT) -> HRESULT {
        DRAGDROP_S_USEDEFAULTCURSORS
    }
}

/// The drop source for a drag from a window without mouse messages.
pub fn source() -> IDropSource {
    PolledSource.into()
}

/// A point packed as a mouse message carries it (`MAKELPARAM(x, y)`).
const fn packed(point: POINT) -> isize {
    let x = point.x as u16 as u32;
    let y = point.y as u16 as u32;
    ((y << 16) | x).cast_signed() as isize
}

/// Wakes the drag loop of the thread that made it, until dropped.
pub struct Pulse {
    running: Arc<AtomicBool>,
}

impl Pulse {
    pub fn start() -> Self {
        let running = Arc::new(AtomicBool::new(true));
        // SAFETY: no preconditions.
        let thread = unsafe { GetCurrentThreadId() };
        let keep = Arc::clone(&running);
        let spawned = std::thread::Builder::new()
            .name("drag-pulse".to_owned())
            .spawn(move || {
                while keep.load(Ordering::Acquire) {
                    let mut cursor = POINT::default();
                    // The loop finds what is under the drag from the message's
                    // place, not from the pointer's: a move without one would
                    // leave the target where the drag began.
                    // SAFETY: `cursor` is writable.
                    if unsafe { GetCursorPos(&raw mut cursor) }.is_ok() {
                        // SAFETY: posting to a thread of this process; without
                        // a queue there the call just fails.
                        let _ = unsafe {
                            PostThreadMessageW(
                                thread,
                                WM_MOUSEMOVE,
                                WPARAM(MK_LBUTTON.0 as usize),
                                LPARAM(packed(cursor)),
                            )
                        };
                    }
                    std::thread::sleep(PULSE);
                }
            });
        if spawned.is_err() {
            // Without the helper the drag still ends on Escape.
            running.store(false, Ordering::Release);
        }
        Self { running }
    }
}

impl Drop for Pulse {
    fn drop(&mut self) {
        self.running.store(false, Ordering::Release);
    }
}

#[cfg(test)]
mod tests {
    use super::{Next, POINT, decide, packed};

    #[test]
    fn escape_gives_up_and_the_button_going_up_drops() {
        assert_eq!(decide(false, true), Next::Continue);
        assert_eq!(decide(false, false), Next::Drop);
        assert_eq!(decide(true, true), Next::Cancel);
        assert_eq!(decide(true, false), Next::Cancel);
    }

    #[test]
    fn a_place_is_packed_as_a_mouse_message_carries_it() {
        assert_eq!(packed(POINT { x: 2770, y: 885 }), (0x375 << 16) | 0xAD2);
        // Screens left of or above the main one have negative places.
        let negative = packed(POINT { x: -5, y: -1 }) as u32;
        assert_eq!(negative & 0xFFFF, 0xFFFB);
        assert_eq!(negative >> 16, 0xFFFF);
    }
}
